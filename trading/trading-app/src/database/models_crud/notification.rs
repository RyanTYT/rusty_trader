use crate::database::{
    crud::{CRUD, CRUDTrait},
    db::{DbError, Exec},
    models::{NotificationFullKeys, NotificationPrimaryKeys, NotificationUpdateKeys},
};

pub struct NotificationCRUD<'a> {
    pub(super) crud:
        CRUD<'a, NotificationFullKeys, NotificationPrimaryKeys, NotificationUpdateKeys>,
}

// Append-only table (`trading.notifications.id` is GENERATED ALWAYS): only
// the two operations the application legitimately needs are exposed. The
// unsupported CRUD methods do not exist on this type, so using them is a
// compile error (E0599). The inner `CRUD` is private.
#[hotpath::measure_all]
impl<'a> NotificationCRUD<'a> {
    pub fn new(exec: Exec<'a>) -> Self {
        Self {
            crud: CRUD::<NotificationFullKeys, NotificationPrimaryKeys, NotificationUpdateKeys>::new(
                exec,
                "trading.notifications",
            ),
        }
    }

    /// Append one notification. The identity `id` is generated by the
    /// database; callers pass `NotificationFullKeys { id: None, .. }`.
    pub async fn create(&mut self, full_keys: &NotificationFullKeys) -> Result<(), DbError> {
        CRUDTrait::create(&mut self.crud, full_keys).await
    }

    pub async fn read_all(&mut self) -> Result<Vec<NotificationFullKeys>, DbError> {
        CRUDTrait::read_all(&mut self.crud).await
    }
}
