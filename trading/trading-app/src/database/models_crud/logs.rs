//! `logs.logs` — append-only application logging.
//!
//! The table's `id` is `GENERATED ALWAYS`; this wrapper deliberately exposes
//! only [`LogsCRUD::create`](crate::database::models_crud::logs::LogsCRUD::create) and [`LogsCRUD::read_all`](crate::database::models_crud::logs::LogsCRUD::read_all), so addressing or
//! upserting a log row is a compile error. `LogsFullKeys.id` is `None` on
//! insert and `Some(id)` on read. Rows may share `(time, level, name)`, so
//! there is no natural upsert key.
//!
//! # Example
//!
//! ```no_run
//! use chrono::Utc;
//! use trading_app::database::db::DbDirect;
//! use trading_app::database::models::LogsFullKeys;
//! use trading_app::database::tables::DbTables;
//!
//! # async fn example(pool: &sqlx::PgPool) -> Result<(), Box<dyn std::error::Error>> {
//! let mut db = DbDirect::connect(pool);
//! db.logs()
//!     .create(&LogsFullKeys {
//!         id: None,
//!         time: Utc::now(),
//!         level: "INFO".into(),
//!         name: "example".into(),
//!         message: "hello".into(),
//!     })
//!     .await?;
//!
//! let recent = db.logs().read_all().await?;
//! # let _ = recent;
//! # Ok(())
//! # }
//! ```

use crate::database::{
    crud::{CRUD, CRUDTrait},
    db::{DbError, Exec},
    models::{LogsFullKeys, LogsPrimaryKeys, LogsUpdateKeys},
};

pub struct LogsCRUD<'a> {
    pub(super) crud: CRUD<'a, LogsFullKeys, LogsPrimaryKeys, LogsUpdateKeys>,
}

// Append-only table (`logs.logs.id` is GENERATED ALWAYS): only the two
// operations the application legitimately needs are exposed. `update`,
// `delete`, `create_or_update` and address-based reads do not exist on this
// type, so using them is a compile error (E0599) rather than a runtime
// failure. The inner `CRUD` is private.
#[hotpath::measure_all]
impl<'a> LogsCRUD<'a> {
    pub fn new(exec: Exec<'a>) -> Self {
        Self {
            crud: CRUD::<LogsFullKeys, LogsPrimaryKeys, LogsUpdateKeys>::new(exec, "logs.logs"),
        }
    }

    /// Append one log row. The identity `id` is generated by the database;
    /// callers pass `LogsFullKeys { id: None, .. }`.
    pub async fn create(&mut self, full_keys: &LogsFullKeys) -> Result<(), DbError> {
        CRUDTrait::create(&mut self.crud, full_keys).await
    }

    pub async fn read_all(&mut self) -> Result<Vec<LogsFullKeys>, DbError> {
        CRUDTrait::read_all(&mut self.crud).await
    }
}
