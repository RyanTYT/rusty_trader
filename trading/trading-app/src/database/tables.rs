use crate::database::models_crud::transactions::stock_transactions::StockTransactionsCRUD;
use crate::database::models_crud::transactions::transactions::TransactionsCRUD;

/// One accessor per table, implemented for every `DbConn`.
///
/// Each method borrows the session for the lifetime of the returned model
/// handle; call operations before requesting the next handle. Interface
/// accessors (`asset: &AssetType`) select the stock/option/forex table and
/// wrap it in the matching enum; concrete accessors skip the enum when the
/// asset class is statically known.
///
/// # Example
///
/// ```no_run
/// use trading_app::database::crud::CRUDTrait;
/// use trading_app::database::db::DbTxn;
/// use trading_app::database::models::AssetType;
/// use trading_app::database::tables::DbTables;
///
/// # async fn example(pool: &sqlx::PgPool) -> Result<(), Box<dyn std::error::Error>> {
/// let mut txn = DbTxn::begin(pool).await?;
/// let open = txn.open_orders(&AssetType::Stock).read_all().await?;
/// let pending = txn.staged_commissions().read_all().await?;
/// txn.commit().await?;
/// # let _ = (open, pending);
/// # Ok(())
/// # }
/// ```
pub trait DbTables: DbConn {
    // ── standalone tables ──────────────────────────────────────────────
    /// Logs table (`logs.logs`). Append-only: the wrapper exposes `create`
    /// and `read_all` only (identity `id` is generated by the database).
    fn logs(&mut self) -> LogsCRUD<'_> {
        LogsCRUD::new(self.exec())
    }

    /// Strategy registry (`trading.strategy`): one row per strategy name and
    /// its lifecycle status. Most other tables reference it by name.
    fn strategy(&mut self) -> StrategyCRUD<'_> {
        StrategyCRUD::new(self.exec())
    }

    /// Notifications table (`trading.notifications`). Append-only: `create`
    /// and `read_all` only (identity `id` is generated).
    fn notification(&mut self) -> NotificationCRUD<'_> {
        NotificationCRUD::new(self.exec())
    }

    /// Cancelled-order audit log (`logs.cancelled_orders`), keyed by
    /// `(time, order_perm_id, order_id)` and referencing `trading.strategy`.
    fn cancelled_orders(&mut self) -> CancelledOrdersCRUD<'_> {
        CancelledOrdersCRUD::new(self.exec())
    }

    /// Commissions awaiting a fill (`trading.staged_commissions`). Database
    /// triggers apply the fee to the matching transaction.
    fn staged_commissions(&mut self) -> StagedCommissionsCRUD<'_> {
        StagedCommissionsCRUD::new(self.exec())
    }

    // ── open orders ────────────────────────────────────────────────────
    /// Open orders for the given asset class. Returns the stock/option enum;
    /// keys and rows must carry the same variant or the call fails with
    /// [`crate::database::db::DbError::KeyVariantMismatch`].
    fn open_orders(&mut self, asset: &AssetType) -> OpenOrdersCRUD<'_> {
        OpenOrdersCRUD::from_exec(asset, self.exec())
    }

    /// Concrete stock open-orders table; use when the asset class is known
    /// statically and enum dispatch is unnecessary.
    fn open_stock_orders(&mut self) -> OpenStockOrdersCRUD<'_> {
        OpenStockOrdersCRUD::new(self.exec())
    }

    /// Concrete option open-orders table (keyed by the full option identity
    /// plus `perm_id`/`order_id`).
    fn open_option_orders(&mut self) -> OpenOptionOrdersCRUD<'_> {
        OpenOptionOrdersCRUD::new(self.exec())
    }

    // ── current positions ──────────────────────────────────────────────
    /// Current positions for the given asset class (asset-class enum
    /// dispatch). `CASH:<currency>` rows live in the stock table.
    fn current_positions(&mut self, asset: &AssetType) -> CurrentPositionsCRUD<'_> {
        CurrentPositionsCRUD::from_exec(asset, self.exec())
    }

    /// Concrete stock/cash positions table
    /// (`trading.current_stock_positions`), including `CASH:<currency>` rows.
    fn current_stock_positions(&mut self) -> CurrentStockPositionsCRUD<'_> {
        CurrentStockPositionsCRUD::new(self.exec())
    }

    /// Concrete option positions table (`trading.current_option_positions`).
    fn current_option_positions(&mut self) -> CurrentOptionPositionsCRUD<'_> {
        CurrentOptionPositionsCRUD::new(self.exec())
    }

    // ── target positions ───────────────────────────────────────────────
    /// Target positions for the given asset class (asset-class enum dispatch).
    /// Targets are desired end states; the engine diffs them against current
    /// positions to size orders.
    fn target_positions(&mut self, asset: &AssetType) -> TargetPositionsCRUD<'_> {
        TargetPositionsCRUD::from_exec(asset, self.exec())
    }

    /// Concrete stock target table (`trading.target_stock_positions`), keyed
    /// by strategy plus instrument.
    fn target_stock_positions(&mut self) -> TargetStockPositionsCRUD<'_> {
        TargetStockPositionsCRUD::new(self.exec())
    }

    /// Concrete option target table (`trading.target_option_positions`),
    /// keyed by the full option identity plus strategy.
    fn target_option_positions(&mut self) -> TargetOptionPositionsCRUD<'_> {
        TargetOptionPositionsCRUD::new(self.exec())
    }

    // ── transactions ───────────────────────────────────────────────────
    /// Executions/fills for the given asset class (asset-class enum dispatch).
    /// Each execution is recorded once; commissions are applied by trigger.
    fn transactions(&mut self, asset: &AssetType) -> TransactionsCRUD<'_> {
        TransactionsCRUD::from_exec(asset, self.exec())
    }

    /// Concrete stock executions table (`trading.stock_transactions`), keyed
    /// by `execution_id`.
    fn stock_transactions(&mut self) -> StockTransactionsCRUD<'_> {
        StockTransactionsCRUD::new(self.exec())
    }

    /// Concrete option executions table (`trading.option_transactions`),
    /// keyed by `execution_id`.
    fn option_transactions(&mut self) -> OptionTransactionsCRUD<'_> {
        OptionTransactionsCRUD::new(self.exec())
    }

    // ── historical data ────────────────────────────────────────────────
    /// Historical bars for the given asset class (asset-class enum dispatch:
    /// stock, options, or forex).
    fn historical_data(&mut self, asset: &AssetType) -> HistoricalDataCRUD<'_> {
        HistoricalDataCRUD::from_exec(asset, self.exec())
    }

    /// Concrete stock bar table (`market_data.historical_data`), a TimescaleDB
    /// hypertable keyed by instrument plus `time`.
    fn historical_stock_data(&mut self) -> HistoricalStockDataCRUD<'_> {
        HistoricalStockDataCRUD::new(self.exec())
    }

    /// Concrete option bar table (`market_data.historical_options_data`),
    /// keyed by the full option identity plus `time`.
    fn historical_options_data(&mut self) -> HistoricalOptionsDataCRUD<'_> {
        HistoricalOptionsDataCRUD::new(self.exec())
    }

    /// Concrete forex bar table (`market_data.historical_forex_data`), keyed
    /// by pair plus `time`.
    fn historical_forex_data(&mut self) -> HistoricalForexDataCRUD<'_> {
        HistoricalForexDataCRUD::new(self.exec())
    }
}

/// Blanket implementation: every session (including `?Sized` trait objects)
/// gains the table accessors for free.
impl<T: DbConn + ?Sized> DbTables for T {}
