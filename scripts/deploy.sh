#!/usr/bin/env bash
set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

SSH_TARGET="${SSH_TARGET:-trader@10.10.10.13}"
SSH_KEY="${SSH_KEY:-}"
REMOTE_DIR="${REMOTE_DIR:-/opt/autotrader}"
TAG="${TAG:-}"
ENV_FILE="${ENV_FILE:-$ROOT/.env}"
IBC_SOURCE="${IBC_CONFIG_SOURCE:-}"
ALERTMANAGER_SOURCE=""

SYNC_ENV=1
SYNC_IBC=1
CONSOLE="${HOTPATH_CONSOLE:-1}"
SKIP_BUILD=0
DRY_RUN=0
NO_HEALTH=0
ALLOW_DIRTY=0
HEALTH_OK=0
KEEP_IMAGES="${KEEP_IMAGES:-3}"
PRUNE_IMAGES="${PRUNE_IMAGES:-ask}"

usage() {
    cat <<'EOF'
Usage: scripts/deploy.sh [options]

Build a release (unless --skip-build), push it to prod, copy the release .env
and IB Gateway config.ini to /opt/autotrader/shared/, switch current, and start
the stacks in order: trading -> platform -> monitoring.

Options:
  --tag TAG             Release tag (default: generated by release.sh)
  --skip-build          Deploy an existing .releases/<tag> bundle
  --with-console        Start hotpath-console on prod (default)
  --without-console     Do not start hotpath-console; stop it if running
  --env-file PATH       Source .env to copy to prod (default: ./.env)
  --ibc-config PATH     Source IB Gateway config.ini
  --alertmanager PATH   Copy a real Alertmanager config to prod
  --no-sync-env         Do not copy/replace prod shared/.env
  --no-sync-ibc         Do not copy/replace prod shared/ib-gateway/config.ini
  --no-health           Skip the HTTP health wait
  --keep-images N       Keep the newest N release images per service (default: 3)
  --prune-images        Delete older release images without asking
  --no-prune-images     Keep all release images
  --allow-dirty         Pass --allow-dirty to release.sh
  --dry-run             Print remote actions without changing prod
  -h, --help            Show this help

Environment overrides: SSH_TARGET, SSH_KEY, REMOTE_DIR, ENV_FILE,
IBC_CONFIG_SOURCE, HOTPATH_CONSOLE, TAG, KEEP_IMAGES, PRUNE_IMAGES.
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --tag)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            TAG="$2"
            shift 2
            ;;
        --skip-build)
            SKIP_BUILD=1
            shift
            ;;
        --with-console)
            CONSOLE=1
            shift
            ;;
        --without-console)
            CONSOLE=0
            shift
            ;;
        --env-file)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            ENV_FILE="$2"
            shift 2
            ;;
        --ibc-config)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            IBC_SOURCE="$2"
            shift 2
            ;;
        --alertmanager)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            ALERTMANAGER_SOURCE="$2"
            shift 2
            ;;
        --no-sync-env)
            SYNC_ENV=0
            shift
            ;;
        --no-sync-ibc)
            SYNC_IBC=0
            shift
            ;;
        --no-health)
            NO_HEALTH=1
            shift
            ;;
        --keep-images)
            [[ $# -ge 2 ]] || { usage; exit 1; }
            KEEP_IMAGES="$2"
            shift 2
            ;;
        --prune-images)
            PRUNE_IMAGES=yes
            shift
            ;;
        --no-prune-images)
            PRUNE_IMAGES=no
            shift
            ;;
        --allow-dirty)
            ALLOW_DIRTY=1
            shift
            ;;
        --dry-run)
            DRY_RUN=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown argument: $1" >&2
            usage
            exit 1
            ;;
    esac
done

if ! [[ "$KEEP_IMAGES" =~ ^[0-9]+$ ]] || [[ "$KEEP_IMAGES" -lt 1 ]]; then
    echo "KEEP_IMAGES must be a positive integer." >&2
    exit 1
fi
case "$PRUNE_IMAGES" in
    ask|yes|no) ;;
    *)
        echo "PRUNE_IMAGES must be ask, yes, or no." >&2
        exit 1
        ;;
esac

if [[ -z "$SSH_KEY" ]]; then
    for candidate in "$HOME/.ssh/autotrader_deploy" "$HOME/.ssh/autotrader-deploy"; do
        if [[ -f "$candidate" ]]; then
            SSH_KEY="$candidate"
            break
        fi
    done
fi
if [[ -z "$SSH_KEY" || ! -f "$SSH_KEY" ]]; then
    echo "SSH key not found. Set SSH_KEY or create ~/.ssh/autotrader_deploy." >&2
    exit 1
fi

if [[ "$CONSOLE" != "0" && "$CONSOLE" != "1" ]]; then
    echo "HOTPATH_CONSOLE must be 0 or 1." >&2
    exit 1
fi

SSH=(ssh -i "$SSH_KEY" -o BatchMode=yes -o ConnectTimeout=10 "$SSH_TARGET")
RSYNC_SSH="ssh -i $SSH_KEY -o BatchMode=yes -o ConnectTimeout=10"

remote() {
    "${SSH[@]}" "$@"
}

run_remote() {
    if [[ "$DRY_RUN" == "1" ]]; then
        printf 'DRY-RUN remote: %s\n' "$*"
    else
        remote "$@"
    fi
}

if docker info >/dev/null 2>&1; then
    DOCKER=(docker)
elif sudo -n docker info >/dev/null 2>&1; then
    DOCKER=(sudo -n docker)
else
    echo "Docker is not accessible (tried docker and sudo -n docker)." >&2
    exit 1
fi

if [[ -z "$TAG" ]]; then
    TAG="$(git show -s --format=%cd --date=format:%Y%m%d-%H%M HEAD)-$(git rev-parse --short HEAD)"
fi

BUNDLE="$ROOT/.releases/$TAG"

if [[ "$SYNC_ENV" == "1" && ! -f "$ENV_FILE" ]]; then
    echo "Missing $ENV_FILE. Create it from .env.example, pass --env-file, or use --no-sync-env." >&2
    exit 1
fi

read_env_value() {
    local key="$1"
    awk -v key="$key" '
        BEGIN { FS = "=" }
        $1 == key { sub(/^[^=]*=/, ""); print; exit }
    ' "$ENV_FILE" 2>/dev/null || true
}

if [[ "$SYNC_IBC" == "1" && -z "$IBC_SOURCE" ]]; then
    ibc_value="$(read_env_value IBC_CONFIG_PATH)"
    ibc_value="${ibc_value%\"}"
    ibc_value="${ibc_value#\"}"
    if [[ -n "$ibc_value" ]]; then
        if [[ "$ibc_value" == /* ]]; then
            IBC_SOURCE="$ibc_value"
        else
            IBC_SOURCE="$(cd "$ROOT/compose" && realpath -m "$ibc_value")"
        fi
    else
        IBC_SOURCE="$ROOT/infra/ib-gateway/IBCMacos-3.20.0/config.ini"
    fi
fi

if [[ "$SYNC_IBC" == "1" && ! -f "$IBC_SOURCE" ]]; then
    echo "IB Gateway config not found: $IBC_SOURCE" >&2
    echo "Pass --ibc-config PATH or --no-sync-ibc." >&2
    exit 1
fi

if [[ -n "$ALERTMANAGER_SOURCE" && ! -f "$ALERTMANAGER_SOURCE" ]]; then
    echo "Alertmanager config not found: $ALERTMANAGER_SOURCE" >&2
    exit 1
fi

remote "set -e
command -v rsync >/dev/null
command -v zstd >/dev/null
sudo -n docker info >/dev/null
sudo -n docker compose version >/dev/null
test -d '$REMOTE_DIR'"

if [[ "$SKIP_BUILD" == "0" && "$DRY_RUN" == "1" ]]; then
    echo "DRY-RUN: skipping release build; use --skip-build with an existing tag to inspect a real bundle."
    SKIP_BUILD=1
fi

if [[ "$SKIP_BUILD" == "0" ]]; then
    release_args=(--tag "$TAG")
    [[ "$CONSOLE" == "0" ]] && release_args+=(--without-console)
    [[ "$ALLOW_DIRTY" == "1" ]] && release_args+=(--allow-dirty)
    "$ROOT/scripts/release.sh" "${release_args[@]}"
else
    [[ -d "$BUNDLE" ]] || { echo "Release bundle not found: $BUNDLE" >&2; exit 1; }
fi

MANIFEST="$BUNDLE/images.txt"
[[ -f "$MANIFEST" ]] || { echo "Missing image manifest: $MANIFEST" >&2; exit 1; }
if [[ "$CONSOLE" == "1" ]] && ! grep -q 'rusty_trader/hotpath-console:' "$MANIFEST"; then
    echo "Release $TAG has no hotpath-console image; rebuild without --without-console." >&2
    exit 1
fi

missing=()
while IFS=$'\t' read -r image id; do
    [[ -n "$image" ]] || continue
    remote_id="$(remote "sudo -n docker image inspect --format '{{.Id}}' '$image' 2>/dev/null" </dev/null || true)"
    remote_id="${remote_id//$'\r'/}"
    remote_id="${remote_id//$'\n'/}"
    if [[ "$remote_id" != "$id" ]]; then
        missing+=("$image")
    fi
done < "$MANIFEST"

if [[ ${#missing[@]} -gt 0 ]]; then
    if [[ "$DRY_RUN" == "1" ]]; then
        printf 'DRY-RUN: would transfer %s\n' "${missing[*]}"
    else
        echo "Transferring ${#missing[@]} image(s)..."
        "${DOCKER[@]}" save "${missing[@]}" | zstd -T0 | remote "zstd -d | sudo -n docker load"
    fi
fi

run_remote "mkdir -p '$REMOTE_DIR/releases/$TAG'"
run_remote "mkdir -p '$REMOTE_DIR/shared/ib-gateway'"
if [[ "$DRY_RUN" == "1" ]]; then
    printf 'DRY-RUN: rsync %s/ -> %s:%s/releases/%s/\n' "$BUNDLE" "$SSH_TARGET" "$REMOTE_DIR" "$TAG"
else
    rsync -az --delete -e "$RSYNC_SSH" "$BUNDLE/" "$SSH_TARGET:$REMOTE_DIR/releases/$TAG/"
fi

remote_alertmanager=0
if [[ -n "$ALERTMANAGER_SOURCE" ]] || remote "test -f '$REMOTE_DIR/shared/alertmanager.yml'"; then
    remote_alertmanager=1
fi

if [[ "$SYNC_ENV" == "1" ]]; then
    tmp_env="$(mktemp)"
    trap 'rm -f "$tmp_env"' EXIT
    chmod 600 "$tmp_env"
    grep -v -E '^(IMAGE_TAG|IBC_CONFIG_PATH|ALERTMANAGER_CONFIG)=' "$ENV_FILE" > "$tmp_env" || true
    {
        printf '\nIMAGE_TAG=%s\n' "$TAG"
        printf 'IBC_CONFIG_PATH=%s\n' "$REMOTE_DIR/shared/ib-gateway/config.ini"
        if [[ "$remote_alertmanager" == "1" ]]; then
            printf 'ALERTMANAGER_CONFIG=%s\n' "$REMOTE_DIR/shared/alertmanager.yml"
        fi
    } >> "$tmp_env"

    if remote "test -f '$REMOTE_DIR/shared/.env'"; then
        run_remote "cp -p '$REMOTE_DIR/shared/.env' '$REMOTE_DIR/shared/.env.bak.$TAG'"
    fi
    if [[ "$DRY_RUN" == "1" ]]; then
        echo "DRY-RUN: would copy transformed $ENV_FILE -> $REMOTE_DIR/shared/.env"
    else
        rsync -a --chmod=F600 -e "$RSYNC_SSH" "$tmp_env" "$SSH_TARGET:$REMOTE_DIR/shared/.env"
    fi
fi

if [[ "$SYNC_IBC" == "1" ]]; then
    if remote "test -f '$REMOTE_DIR/shared/ib-gateway/config.ini'"; then
        run_remote "cp -p '$REMOTE_DIR/shared/ib-gateway/config.ini' '$REMOTE_DIR/shared/ib-gateway/config.ini.bak.$TAG'"
    fi
    if [[ "$DRY_RUN" == "1" ]]; then
        echo "DRY-RUN: would copy $IBC_SOURCE -> $REMOTE_DIR/shared/ib-gateway/config.ini"
    else
        rsync -a --chmod=F600 -e "$RSYNC_SSH" "$IBC_SOURCE" "$SSH_TARGET:$REMOTE_DIR/shared/ib-gateway/config.ini"
    fi
fi

if [[ -n "$ALERTMANAGER_SOURCE" ]]; then
    if remote "test -f '$REMOTE_DIR/shared/alertmanager.yml'"; then
        run_remote "cp -p '$REMOTE_DIR/shared/alertmanager.yml' '$REMOTE_DIR/shared/alertmanager.yml.bak.$TAG'"
    fi
    if [[ "$DRY_RUN" == "1" ]]; then
        echo "DRY-RUN: would copy $ALERTMANAGER_SOURCE -> $REMOTE_DIR/shared/alertmanager.yml"
    else
        rsync -a --chmod=F600 -e "$RSYNC_SSH" "$ALERTMANAGER_SOURCE" "$SSH_TARGET:$REMOTE_DIR/shared/alertmanager.yml"
    fi
fi

run_remote "ln -sfn 'releases/$TAG' '$REMOTE_DIR/current'"
run_remote "sudo -n docker network inspect autotrader >/dev/null 2>&1 || sudo -n docker network create autotrader"

profile_args=""
[[ "$CONSOLE" == "1" ]] && profile_args="--profile console"

run_remote "cd '$REMOTE_DIR/current' && sudo -n docker compose --env-file '$REMOTE_DIR/shared/.env' -f compose/trading.yml $profile_args up -d"
if [[ "$CONSOLE" == "0" ]]; then
    run_remote "cd '$REMOTE_DIR/current' && sudo -n docker compose --env-file '$REMOTE_DIR/shared/.env' -f compose/trading.yml --profile console stop hotpath-console >/dev/null 2>&1 || true"
fi
run_remote "cd '$REMOTE_DIR/current' && sudo -n docker compose --env-file '$REMOTE_DIR/shared/.env' -f compose/platform.yml up -d"
run_remote "cd '$REMOTE_DIR/current' && sudo -n docker compose --env-file '$REMOTE_DIR/shared/.env' -f compose/monitoring.yml up -d"

if [[ "$NO_HEALTH" == "0" && "$DRY_RUN" == "0" ]]; then
    if remote "command -v curl >/dev/null 2>&1"; then
        echo "Waiting for trading and backend health..."
        for _ in $(seq 1 36); do
            trading_ok=0
            backend_ok=0
            remote "curl -fsS --max-time 3 http://127.0.0.1:8000/check-health >/dev/null 2>&1" && trading_ok=1 || true
            remote "curl -fsS --max-time 3 http://127.0.0.1:3000/check-health >/dev/null 2>&1" && backend_ok=1 || true
            if [[ "$trading_ok" == "1" && "$backend_ok" == "1" ]]; then
                echo "Health checks passed."
                HEALTH_OK=1
                break
            fi
            sleep 5
        done
        if [[ "$trading_ok" != "1" || "$backend_ok" != "1" ]]; then
            echo "Health checks did not pass within 180s. Inspect with:" >&2
            echo "  ssh -i $SSH_KEY $SSH_TARGET 'cd $REMOTE_DIR/current && sudo -n docker compose --env-file $REMOTE_DIR/shared/.env -f compose/trading.yml ps'" >&2
        fi
    else
        echo "curl not found on prod; skipping HTTP health checks."
        HEALTH_OK=1
    fi
fi

prune_old_images() {
    [[ "$DRY_RUN" == "1" || "$PRUNE_IMAGES" == "no" ]] && return

    local list image reply
    list="$(remote "sudo -n docker image ls --format '{{.Repository}}:{{.Tag}}' | grep -E '^rusty_trader/[^:]+:[0-9]{8}-[0-9]{4}-[0-9a-f]+$' | sort -t: -k1,1 -k2,2r | awk -F: -v keep=$KEEP_IMAGES '{ count[\$1]++; if (count[\$1] > keep) print }'")"
    [[ -n "$list" ]] || return

    echo
    echo "Old release images (keeping the newest $KEEP_IMAGES per service):"
    while IFS= read -r image; do
        [[ -n "$image" ]] && echo "  $image"
    done <<< "$list"

    if [[ "$PRUNE_IMAGES" == "ask" ]]; then
        if [[ -r /dev/tty ]]; then
            read -r -p "Remove these images? [Y/n] " reply </dev/tty || reply=""
        else
            echo "No TTY available; keeping old images. Use --prune-images to remove them."
            return
        fi
        case "${reply:-y}" in
            y|Y|yes|YES) ;;
            *)
                echo "Keeping old images."
                return
                ;;
        esac
    fi

    while IFS= read -r image; do
        [[ -n "$image" ]] || continue
        if remote "sudo -n docker image rm '$image'" >/dev/null 2>&1; then
            echo "Removed $image"
        else
            echo "Skipped $image (in use or already missing)"
        fi
    done <<< "$list"
}

if [[ "$NO_HEALTH" == "1" || "$HEALTH_OK" == "1" ]]; then
    prune_old_images
else
    echo "Health checks did not pass; keeping old images for rollback."
fi

if [[ "$DRY_RUN" == "1" ]]; then
    echo "DRY-RUN complete for $TAG; no prod changes."
else
    echo "Deployed $TAG to $SSH_TARGET:$REMOTE_DIR/current"
fi
echo "Console: $([[ "$CONSOLE" == "1" ]] && echo included || echo excluded)"
